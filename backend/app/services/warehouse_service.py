    @staticmethod
    def get_table_schema(table_name: str) -> Optional[Dict[str, Any]]:
        conn = WarehouseService.get_connection()
        cur = conn.cursor()
        try:
            cur.execute(f"PRAGMA table_info({table_name})")
            rows = cur.fetchall()
            if not rows:
                return None

            columns = []
            for r in rows:
                col_name = r[1]
                col_type = r[2]
                is_pk = (r[5] == 1)

                cur.execute(f"SELECT COUNT(*) FROM {table_name} WHERE {col_name} IS NULL")
                null_count = cur.fetchone()[0]

                cur.execute(f"SELECT COUNT(DISTINCT {col_name}) FROM {table_name}")
                distinct_sample = cur.fetchone()[0]

                columns.append({
                    "name": col_name,
                    "type": col_type,
                    "is_primary_key": is_pk,
                    "null_count": null_count,
                    "distinct_sample": distinct_sample
                })

            cur.execute(f"SELECT COUNT(*) FROM {table_name}")
            total_rows = cur.fetchone()[0]

            return {
                "table_name": table_name,
                "total_rows": total_rows,
                "total_columns": len(columns),
                "columns": columns
            }
        except Exception as e:
            logger.error(f"Error fetching schema for {table_name}: {e}")
            return None

    @staticmethod
    def get_table_data(
        table_name: str,
        page: int = 1,
        page_size: int = 20,
        sort_by: Optional[str] = None,
        sort_dir: str = "asc",
        search: Optional[str] = None
    ) -> Dict[str, Any]:
        conn = WarehouseService.get_connection()
        cur = conn.cursor()

        if table_name not in WarehouseService._loaded_tables:
            return {"error": f"Table '{table_name}' does not exist.", "total": 0, "rows": []}

        offset = (page - 1) * page_size
        where_clause = ""
        params = []

        cur.execute(f"PRAGMA table_info({table_name})")
        col_infos = cur.fetchall()
        col_names = [c[1] for c in col_infos]

        if isinstance(search, str) and search.strip():
            search_term = f"%{search.strip()}%"
            search_conditions = []
            for c in col_names:
                search_conditions.append(f"CAST({c} AS TEXT) LIKE ?")
                params.append(search_term)
            where_clause = f"WHERE {' OR '.join(search_conditions)}"

        count_query = f"SELECT COUNT(*) FROM {table_name} {where_clause}"
        cur.execute(count_query, params)
        total_records = cur.fetchone()[0]

        order_clause = ""
        if isinstance(sort_by, str) and sort_by in col_names:
            direction = "DESC" if isinstance(sort_dir, str) and sort_dir.lower() == "desc" else "ASC"
            order_clause = f"ORDER BY {sort_by} {direction}"

        data_query = f"SELECT * FROM {table_name} {where_clause} {order_clause} LIMIT ? OFFSET ?"
        fetch_params = params + [page_size, offset]
        cur.execute(data_query, fetch_params)

        rows = []
        for r in cur.fetchall():
            rows.append(dict(zip(col_names, r)))

        return {
            "table_name": table_name,
            "page": page,
            "page_size": page_size,
            "total_records": total_records,
            "total_pages": (total_records + page_size - 1) // page_size if total_records > 0 else 1,
            "columns": col_names,
            "rows": rows
        }

