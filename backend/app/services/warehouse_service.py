    @staticmethod
    def execute_safe_sql(query: str, max_rows: int = 100) -> Dict[str, Any]:
        """
        Executes a read-only SQL query safely against the in-memory SQLite warehouse cache.
        Blocks any DDL/DML statements (DROP, INSERT, UPDATE, DELETE, ALTER, etc.).
        """
        clean_query = query.strip()

        if not clean_query:
            return {"success": False, "error": "Query cannot be empty."}

        upper_query = clean_query.upper()
        if not (upper_query.startswith("SELECT") or upper_query.startswith("WITH")):
            return {
                "success": False,
                "error": "Only read-only SELECT or WITH (Common Table Expression) queries are permitted."
            }

        forbidden = ["DROP", "DELETE", "UPDATE", "INSERT", "ALTER", "TRUNCATE", "REPLACE", "CREATE", "ATTACH", "DETACH"]
        for word in forbidden:
            if f" {word} " in f" {upper_query} " or upper_query.startswith(f"{word} "):
                return {
                    "success": False,
                    "error": f"Security Exception: Modifying keyword '{word}' is not permitted in read-only SQL workspace."
                }

        conn = WarehouseService.get_connection()
        cur = conn.cursor()

        start_time = time.time()
        try:
            cur.execute(clean_query)
            cols = [desc[0] for desc in cur.description] if cur.description else []
            raw_rows = cur.fetchmany(max_rows)
            execution_time_ms = round((time.time() - start_time) * 1000, 2)

            rows = []
            for r in raw_rows:
                rows.append(dict(zip(cols, r)))

            return {
                "success": True,
                "execution_time_ms": execution_time_ms,
                "row_count": len(rows),
                "columns": cols,
                "rows": rows,
                "engine": "In-Memory Data Warehouse SQL Engine (SQLite 3.x with PostgreSQL DDL Support)",
                "truncated": len(raw_rows) == max_rows
            }
        except Exception as e:
            execution_time_ms = round((time.time() - start_time) * 1000, 2)
            return {
                "success": False,
                "execution_time_ms": execution_time_ms,
                "error": str(e)
            }
