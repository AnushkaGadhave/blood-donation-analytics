logger = logging.getLogger("WarehouseService")


class WarehouseService:
    _instance = None
    _db_conn = None
    _loaded_tables = set()

    @classmethod
    def get_connection(cls) -> sqlite3.Connection:
        if cls._db_conn is None:
            cls._db_conn = sqlite3.connect(":memory:", check_same_thread=False)
            cls._load_all_tables(cls._db_conn)
        return cls._db_conn

    @classmethod
    def _load_all_tables(cls, conn: sqlite3.Connection):
        # Guarantee Lab 01 pipeline has generated physical warehouse CSV artifacts
        try:
            Lab1Service.execute_and_export_lab1()
        except Exception as e:
            logger.error(f"Error initializing Lab1 warehouse pipeline: {e}")

        output_dir = Lab1Service.get_output_dir()
        schema_dirs = [
            os.path.join(output_dir, "star_schema"),
            os.path.join(output_dir, "snowflake_schema"),
            os.path.join(output_dir, "fact_constellation"),
        ]

        loaded_table_names = set()

        for s_dir in schema_dirs:
            if not os.path.exists(s_dir):
                continue
            for fname in os.listdir(s_dir):
                if fname.endswith(".csv"):
                    table_name = fname.replace(".csv", "")
                    # Avoid duplicate load if already loaded
                    if table_name in loaded_table_names:
                        continue
                    csv_path = os.path.join(s_dir, fname)
                    try:
                        df = pd.read_csv(csv_path)
                        df.to_sql(table_name, conn, if_exists="replace", index=False)
                        cls._loaded_tables.add(table_name)
                        loaded_table_names.add(table_name)
                        logger.info(f"Loaded warehouse table '{table_name}' ({len(df)} rows) into SQLite engine.")
                    except Exception as e:
                        logger.error(f"Failed to load warehouse table '{table_name}': {e}")

